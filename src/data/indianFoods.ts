export const getFoodEmoji = (foodName: string, category?: string): string => {
  const name = foodName.toLowerCase();
  if (name.includes('biryani') || name.includes('chawal') || name.includes('rice')) return '🍛';
  if (name.includes('paneer') || name.includes('cheese')) return '🧀';
  if (name.includes('roti') || name.includes('chapati') || name.includes('naan') || name.includes('paratha')) return '🫓';
  if (name.includes('dal') || name.includes('khichdi') || name.includes('sambar') || name.includes('soup')) return '🥣';
  if (name.includes('idli')) return '⚪';
  if (name.includes('dosa')) return '🥞';
  if (name.includes('samosa')) return '🔺';
  if (name.includes('bhature') || name.includes('puri')) return '🥖';
  if (name.includes('chicken') || name.includes('tikka') || name.includes('tandoori')) return '🍗';
  if (name.includes('gulab') || name.includes('jamun') || name.includes('halwa') || name.includes('sweet') || name.includes('rasgulla') || name.includes('jalebi')) return '🍩';
  if (name.includes('vada')) return '🍩';
  if (name.includes('upma') || name.includes('poha')) return '🥣';
  if (name.includes('dhokla')) return '🟨';
  if (name.includes('fish') || name.includes('curry')) return '🐟';
  if (name.includes('papad')) return '🍪';
  if (name.includes('lassi') || name.includes('milk') || name.includes('raita')) return '🥛';
  if (name.includes('chai') || name.includes('tea') || name.includes('coffee')) return '☕';
  if (name.includes('bhel') || name.includes('chaat')) return '🍿';
  if (name.includes('pani')) return '🟢';
  
  // Fallback based on category
  if (category === 'Breakfast') return '🍳';
  if (category === 'Main Course') return '🍽️';
  if (category === 'Snacks') return '🍿';
  if (category === 'Desserts') return '🍰';
  return '🍲';
};